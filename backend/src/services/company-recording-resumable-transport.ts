import { parseDriveResumeResponse, validateRecordingChunkRange, type DriveResumeResult } from './company-recording-transfer-protocol.js';

const fileIdPattern = /^[A-Za-z0-9_-]{10,128}$/;
const folderIdPattern = /^[A-Za-z0-9_-]{10,128}$/;
const MAX_BYTES = 8 * 1024 * 1024;
type SessionRejection = 'missing_location' | 'location_too_long' | 'invalid_characters' |
  'malformed_url' | 'non_https' | 'unexpected_host' | 'unexpected_port' |
  'embedded_credentials' | 'fragment' |
  'unexpected_path' | 'invalid_upload_type' | 'invalid_upload_id';
type SessionDiagnostic = { locationPresent: boolean; https: boolean | null;
  allowedGoogleHost: boolean | null; rejection: SessionRejection | null };
export class CompanyRecordingSessionStartError extends Error {
  constructor(readonly kind: 'invalid_metadata' | 'request_failure' | 'http_failure' | 'invalid_session',
    readonly httpStatus?: number, readonly sessionDiagnostic?: SessionDiagnostic) {
    super('Company Drive session initiation failed.');
    this.name = 'CompanyRecordingSessionStartError';
  }
}
function inspectSession(value: string | null): SessionDiagnostic {
  if (value === null || value === '') return { locationPresent: false, https: null, allowedGoogleHost: null, rejection: 'missing_location' };
  if (value.length > 4096) return { locationPresent: true, https: null, allowedGoogleHost: null, rejection: 'location_too_long' };
  if (/[\x00-\x20\x7f]/.test(value)) return { locationPresent: true, https: null, allowedGoogleHost: null, rejection: 'invalid_characters' };
  try {
    const url = new URL(value);
    const result = { locationPresent: true, https: url.protocol === 'https:',
      allowedGoogleHost: url.hostname === 'www.googleapis.com' };
    const id = url.searchParams.get('upload_id');
    if (!result.https) return { ...result, rejection: 'non_https' };
    if (!result.allowedGoogleHost) return { ...result, rejection: 'unexpected_host' };
    if (url.port) return { ...result, rejection: 'unexpected_port' };
    if (url.username || url.password) return { ...result, rejection: 'embedded_credentials' };
    if (url.hash) return { ...result, rejection: 'fragment' };
    if (url.pathname !== '/upload/drive/v3/files') return { ...result, rejection: 'unexpected_path' };
    if (url.searchParams.getAll('uploadType').length !== 1 || url.searchParams.get('uploadType') !== 'resumable')
      return { ...result, rejection: 'invalid_upload_type' };
    if (url.searchParams.getAll('upload_id').length !== 1 || !id || !/^[A-Za-z0-9_-]{1,2048}$/.test(id))
      return { ...result, rejection: 'invalid_upload_id' };
    // The Location URI is generated by Google. Its additional query parameters
    // are opaque session data; keep the complete URI for subsequent PUTs.
    return { ...result, rejection: null };
  } catch { return { locationPresent: true, https: null, allowedGoogleHost: null, rejection: 'malformed_url' }; }
}
function safeSession(value: string): boolean { return inspectSession(value).rejection === null; }

// Injected fetch is required; no application runtime constructs this transport yet.
// Redirects are never followed, including redirects from a persisted session URL.
export class CompanyRecordingResumableTransport {
  constructor(private readonly fetcher: typeof fetch) {}
  private async send(url: string, token: string, init: RequestInit): Promise<Response> {
    if (!token || token.length > 4096) throw new Error('Company Drive access is unavailable.');
    return this.fetcher(url, { ...init, redirect: 'manual',
      headers: { Authorization: `Bearer ${token}`, ...init.headers }, signal: AbortSignal.timeout(20_000) });
  }
  private async checkCompletionId(response: Response, expectedFileId?: string) {
    if (!expectedFileId || (response.status !== 200 && response.status !== 201)) return;
    if (!fileIdPattern.test(expectedFileId)) throw new Error('Invalid company Drive file ID.');
    const reader = response.body?.getReader();
    if (!reader) return;
    const parts: Buffer[] = []; let length = 0;
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      length += value.length;
      if (length > 8192) { await reader.cancel(); throw new Error('Company Drive completion response is too large.'); }
      parts.push(Buffer.from(value));
    }
    if (!length) return;
    let data: { id?: unknown };
    try { data = JSON.parse(Buffer.concat(parts, length).toString('utf8')); }
    catch { throw new Error('Company Drive completion response is invalid.'); }
    if (data.id !== undefined && data.id !== expectedFileId) throw new Error('Company Drive returned an unexpected file ID.');
  }
  async allocateFileId(token: string): Promise<string> {
    const response = await this.send('https://www.googleapis.com/drive/v3/files/generateIds?count=1&space=drive&type=files', token, { method: 'GET' });
    if (response.status !== 200) throw new Error('Company Drive file ID allocation failed.');
    const reader = response.body?.getReader();
    if (!reader) throw new Error('Company Drive file ID allocation failed.');
    const parts: Buffer[] = []; let length = 0;
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      length += value.length;
      if (length > 8192) { await reader.cancel(); throw new Error('Company Drive file ID allocation failed.'); }
      parts.push(Buffer.from(value));
    }
    const body = Buffer.concat(parts, length).toString('utf8');
    let data: { ids?: unknown };
    try { data = JSON.parse(body); } catch { throw new Error('Company Drive file ID allocation failed.'); }
    const id = Array.isArray(data.ids) && data.ids.length === 1 ? data.ids[0] : null;
    if (typeof id !== 'string' || !fileIdPattern.test(id)) throw new Error('Company Drive file ID allocation failed.');
    return id;
  }
  async beginSession(token: string, input: { fileId: string; folderId: string; mimeType: 'video/webm' | 'video/mp4'; byteLength: number; name: string }): Promise<string> {
    if (!fileIdPattern.test(input.fileId) || !folderIdPattern.test(input.folderId) ||
      !['video/webm', 'video/mp4'].includes(input.mimeType) || !Number.isSafeInteger(input.byteLength) ||
      input.byteLength < 1 || input.byteLength > 128 * 1024 * 1024 || input.name.length > 220 || /[\\/:*?"<>|\x00-\x1f\x7f]/.test(input.name) ||
      !(input.mimeType === 'video/mp4' ? /\.mp4$/ : /\.webm$/).test(input.name) || !input.name.trim())
      throw new CompanyRecordingSessionStartError('invalid_metadata');
    let response: Response;
    try {
      response = await this.send('https://www.googleapis.com/upload/drive/v3/files?uploadType=resumable', token, {
        method: 'POST', headers: { 'Content-Type': 'application/json; charset=UTF-8',
          'X-Upload-Content-Type': input.mimeType, 'X-Upload-Content-Length': String(input.byteLength) },
        body: JSON.stringify({ id: input.fileId, name: input.name, mimeType: input.mimeType, parents: [input.folderId] }),
      });
    } catch { throw new CompanyRecordingSessionStartError('request_failure'); }
    if (response.status !== 200) throw new CompanyRecordingSessionStartError('http_failure', response.status);
    const location = response.headers.get('location');
    const diagnostic = inspectSession(location);
    if (location === null || diagnostic.rejection)
      throw new CompanyRecordingSessionStartError('invalid_session', response.status, diagnostic);
    return location;
  }
  async queryOffset(token: string, session: string, total: number, expectedFileId?: string): Promise<DriveResumeResult> {
    if (!safeSession(session)) throw new Error('Invalid company recording session.');
    const response = await this.send(session, token, { method: 'PUT', headers: { 'Content-Length': '0', 'Content-Range': `bytes */${total}` } });
    await this.checkCompletionId(response, expectedFileId);
    return parseDriveResumeResponse(response.status, response.headers.get('range'), total);
  }
  async sendChunk(token: string, session: string, bytes: Buffer, start: number, total: number, expectedFileId?: string): Promise<DriveResumeResult> {
    if (!safeSession(session) || !Buffer.isBuffer(bytes) || bytes.length < 1 || bytes.length > MAX_BYTES)
      throw new Error('Invalid recording chunk.');
    const range = `bytes ${start}-${start + bytes.length - 1}/${total}`;
    validateRecordingChunkRange(range, total, start);
    const response = await this.send(session, token, { method: 'PUT', headers: {
      'Content-Length': String(bytes.length), 'Content-Type': 'application/octet-stream', 'Content-Range': range,
    }, body: new Uint8Array(bytes) });
    await this.checkCompletionId(response, expectedFileId);
    return parseDriveResumeResponse(response.status, response.headers.get('range'), total);
  }
  // Used only to identify an uncertain result by the previously saved file ID.
  // MIME, size, parent and privacy verification remain a separate later phase.
  async lookupFile(token: string, expectedId: string): Promise<'present' | 'absent' | 'unavailable'> {
    if (!fileIdPattern.test(expectedId)) throw new Error('Invalid company Drive file ID.');
    const url = `https://www.googleapis.com/drive/v3/files/${expectedId}?fields=id&supportsAllDrives=false`;
    const response = await this.send(url, token, { method: 'GET' });
    if (response.status === 404) return 'absent';
    if (response.status === 429 || response.status >= 500) return 'unavailable';
    if (response.status !== 200) throw new Error('Company Drive file lookup failed.');
    const reader = response.body?.getReader();
    if (!reader) throw new Error('Company Drive file lookup failed.');
    const parts: Buffer[] = []; let length = 0;
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      length += value.length;
      if (length > 8192) { await reader.cancel(); throw new Error('Company Drive file lookup failed.'); }
      parts.push(Buffer.from(value));
    }
    let file: { id?: unknown };
    try { file = JSON.parse(Buffer.concat(parts, length).toString('utf8')); }
    catch { throw new Error('Company Drive file lookup failed.'); }
    if (file.id !== expectedId) throw new Error('Company Drive returned an unexpected file ID.');
    return 'present';
  }
}
